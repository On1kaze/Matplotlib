"""
Задание 5. Исследование связи между показателями
Дано количество часов подготовки и соответствующие результаты экзамена:
hours = [1, 2, 2, 3, 4, 5, 5, 6, 7, 8]
scores = [48, 52, 55, 60, 65, 70, 73, 78, 84, 90]

Постройте точечный график с помощью функции scatter().
Ответьте на вопросы:
1. Какая связь наблюдается между временем подготовки и результатом?
2. Повышается ли результат при увеличении времени подготовки?
3. Можно ли на основании этого графика утверждать, что продолжительная подготовка
   является единственной причиной высокого результата?
"""

import os
import numpy as np
import matplotlib.pyplot as plt


def run_task5(save_path="images/task5_scatter_plot.png", show=False):
    hours = [1, 2, 2, 3, 4, 5, 5, 6, 7, 8]
    scores = [48, 52, 55, 60, 65, 70, 73, 78, 84, 90]

    plt.figure(figsize=(9, 5.5))
    plt.scatter(
        hours,
        scores,
        color='#2980b9',
        s=85,
        edgecolors='black',
        linewidth=1.2,
        zorder=3,
        label='Данные студентов'
    )

    # Добавляем линию тренда (линейная регрессия)
    z = np.polyfit(hours, scores, 1)
    p = np.poly1d(z)
    x_line = np.linspace(min(hours), max(hours), 100)
    plt.plot(x_line, p(x_line), color='#e74c3c', linestyle='--', linewidth=2, label='Линия тренда (регрессия)')

    for h, s in zip(hours, scores):
        plt.annotate(
            f"({h}ч, {s})",
            (h, s),
            textcoords="offset points",
            xytext=(0, 9),
            ha='center',
            fontsize=9,
            alpha=0.85
        )

    plt.title('Зависимость результата экзамена от времени подготовки', fontsize=14, fontweight='bold', pad=15)
    plt.xlabel('Время подготовки (часы)', fontsize=12)
    plt.ylabel('Результат экзамена (баллы)', fontsize=12)
    plt.xticks(range(1, 9))
    plt.ylim(40, 100)
    plt.grid(True, linestyle='--', alpha=0.7)
    plt.legend(loc='lower right')
    plt.tight_layout()

    answers = {
        "q1": "Наблюдается сильная прямая (положительная) линейная связь: с увеличением времени подготовки результаты экзамена устойчиво растут.",
        "q2": "Да, результат повышается при увеличении времени подготовки. График демонстрирует явную монотонно возрастающую тенденцию.",
        "q3": "Нет, нельзя. Наличие корреляции не означает единственную причинно-следственную связь. На итоговый балл экзамена также влияют многие другие факторы: базовый уровень знаний, индивидуальные способности, качество обучающих материалов, методика подготовки, психологическое состояние и самочувствие."
    }

    print("[Задание 5] Ответы на контрольные вопросы:")
    print(f"  1. Какая связь наблюдается между временем подготовки и результатом?\n     -> {answers['q1']}")
    print(f"  2. Повышается ли результат при увеличении времени подготовки?\n     -> {answers['q2']}")
    print(f"  3. Можно ли утверждать, что продолжительная подготовка является единственной причиной высокого результата?\n     -> {answers['q3']}")

    if save_path:
        os.makedirs(os.path.dirname(save_path), exist_ok=True)
        plt.savefig(save_path, dpi=300)
        print(f"[Задание 5] График сохранён в: {save_path}")

    if show:
        plt.show()
    plt.close()

    return answers


if __name__ == '__main__':
    run_task5(show=True)
